import test from 'node:test';
import assert from 'node:assert/strict';
import {randomUUID} from 'node:crypto';
import {mkdtempSync,rmSync} from 'node:fs';
import {join} from 'node:path';
import {tmpdir} from 'node:os';
import {createStore} from '../plugins/library/legacy/store.mjs';
import {createMobileSyncAdapter} from '../plugins/mobile/src/sync-adapter.mjs';

test('existing and offline topics share IDs, snapshots, guarded writes and durable deletions',async t=>{
  const dir=mkdtempSync(join(tmpdir(),'shiwen-topic-sync-'));
  const dbPath=join(dir,'db.sqlite');
  let store=createStore(dbPath);
  const original=store.themeSave({title:'Desktop',summary:''});
  const source=store.save({kind:'idea',title:'Original',body:'A passage'});
  store.themeMemberAdd({themeId:original.id,revision:1,sourceRecordId:source.id,sourceRevision:source.revision,field:'body'});
  store.close();
  store=createStore(dbPath);
  store.paths={library:dir};
  const host=createMobileSyncAdapter({ctx:{connection:{browserPeer:{id:'test'}}},library:store});
  t.after(()=>{host.close();store.close();rmSync(dir,{recursive:true,force:true});});
  const deviceId=randomUUID();
  const {libraryId,epoch,capabilities}=await host.execute('identity',{deviceId,protocolVersion:'1.0.0-draft.3'});
  assert.equal(capabilities.topicSync,true);
  const call=(action,args={})=>host.execute(action,{deviceId,libraryId,epoch,...args});
  const {heads}=await call('topicHeads');
  const first=await call('topicPage',heads[0]);
  assert.equal(first.members[0].quote,'A passage');
  assert.equal(first.members[0].sourceRecordId,source.id);
  const stamp='2025-03-01T12:00:00.000Z';
  const added={...first.members[0],id:randomUUID(),quote:'passage',whole:false,start:2,end:9,prefix:'A '};
  const op={id:original.id,operationId:randomUUID(),expectedRevision:heads[0].revision,title:'Phone',summary:'Offline edit',
    updated:stamp,titleUpdated:stamp,summaryUpdated:stamp,add:[added],remove:[first.members[0].id]};
  const apply=operation=>call('topicApply',{operation});
  const ack=await apply(op);
  assert.deepEqual(await apply(op),ack);
  assert.deepEqual(store.themeRead({id:op.id}).members.map(m=>[m.id,m.quote]),[[added.id,'passage']]);
  const current=store.themeRead({id:op.id});
  store.themeSave({id:op.id,revision:current.revision,title:'Later desktop edit',summary:op.summary});
  const stale=await apply({...op,operationId:randomUUID(),expectedRevision:ack.revision});
  assert.equal(stale.stale,true);
  const next=await call('topicPage',{id:op.id,revision:stale.revision});
  assert.equal(next.theme.summaryUpdated,stamp);
  assert.notEqual(next.theme.titleUpdated,stamp);
  assert.equal(next.theme.title,'Later desktop edit');
  const deletion={id:op.id,expectedRevision:stale.revision,operationId:randomUUID(),deleted:true,updated:stamp};
  const tombstone=await apply(deletion);
  assert.deepEqual(await apply(deletion),tombstone);
  assert.deepEqual(await call('topicPage',{id:op.id,...tombstone}),{deleted:true,updated:stamp,...tombstone});
  assert.deepEqual(store.themeList(),[]);
  const restored=await apply({...op,expectedRevision:tombstone.revision,operationId:randomUUID(),remove:[]});
  assert.ok(restored.revision>tombstone.revision);
  assert.deepEqual(await apply(deletion),tombstone);
  assert.equal(store.themeList().length,1);
  await assert.rejects(()=>call('topicHeads',{libraryId:randomUUID()}));
});
