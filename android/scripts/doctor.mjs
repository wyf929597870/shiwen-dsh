import {existsSync, readFileSync} from 'node:fs';
import {resolve, join} from 'node:path';
import {spawnSync} from 'node:child_process';
const root = resolve(import.meta.dirname, '..');
const results = [];
const check = (name, ok, detail) => results.push({name, ok: Boolean(ok), detail});
const java = spawnSync('java', ['-version'], {encoding: 'utf8'});
const version = (java.stderr || java.stdout || '').match(/version "(\d+)/)?.[1];
check('Java 21+', Number(version) >= 21, version ? `Java ${version}` : 'java not found');
let localSdk;
const props = resolve(root, 'native/local.properties');
if (existsSync(props)) localSdk = readFileSync(props, 'utf8').match(/^sdk.dir=(.+)$/m)?.[1]?.replaceAll('\\:', ':').replaceAll('\\\\', '\\');
const sdk = localSdk || process.env.ANDROID_HOME || process.env.ANDROID_SDK_ROOT;
check('Android SDK directory', sdk && existsSync(sdk), sdk || 'set ANDROID_HOME or native/local.properties');
check('Android API 36 platform', sdk && existsSync(join(sdk, 'platforms/android-36/android.jar')), 'required for compileSdk 36');
check('Android build-tools 36', sdk && existsSync(join(sdk, 'build-tools/36.0.0/aapt2')), 'install build-tools;36.0.0');
check('Android SDK license', sdk && existsSync(join(sdk, 'licenses/android-sdk-license')), 'review and accept the SDK license using sdkmanager');
check('Capacitor installed', existsSync(resolve(root, 'node_modules/@capacitor/android/package.json')), 'npm ci in android/');
check('Bundled web UI', existsSync(resolve(root, 'dist/index.html')), 'npm run build in android/');
const config = JSON.parse(readFileSync(resolve(root, 'capacitor.config.json'), 'utf8'));
check('Local trusted page only', !config.server?.url && !config.server?.allowNavigation, 'no remote server.url or allowNavigation');
for (const row of results) console.log(`${row.ok ? 'PASS' : 'BLOCKED'} ${row.name}: ${row.detail}`);
if (results.some(row => !row.ok)) process.exitCode = 2;
